#!/bin/bash
# Build the driver against one supported kernel version.
#
# Usage: kernel-tests/build-test.sh <version> [variant]
#   version: 5.4, 5.10, 5.15 or 6.1
#   variant: arm64 (default), arm64be, x86_64, x86_64-clang
#
# The kernel tree is expected in ./linux-<version> (arm64) or
# ./linux-<version>-<variant>. If it is missing, it is extracted from
# kernel-downloads/linux-<version>.*.tar.xz (newest point release) or
# downloaded from kernel.org, then configured and prepared.
#
# Extra make arguments for the driver can be passed in DRIVER_ARGS,
# e.g. DRIVER_ARGS="CONFIG_MP_INCLUDED=y". JOBS defaults to the CPU count.
set -euo pipefail

VERSION=${1:?usage: $0 <kernel version> [variant]}
VARIANT=${2:-arm64}
JOBS=${JOBS:-$(nproc)}
read -r -a DRIVER_ARGS <<< "${DRIVER_ARGS:-}"

cd "$(dirname "$0")/.."

KCONFIG_OPTS=()
case "$VARIANT" in
arm64)
	KSRC=./linux-$VERSION
	MAKE_ARGS=(ARCH=arm64 CROSS_COMPILE=aarch64-linux-gnu-)
	NM=aarch64-linux-gnu-nm
	;;
arm64be)
	KSRC=./linux-$VERSION-$VARIANT
	MAKE_ARGS=(ARCH=arm64 CROSS_COMPILE=aarch64-linux-gnu-)
	NM=aarch64-linux-gnu-nm
	KCONFIG_OPTS=(-d CPU_LITTLE_ENDIAN -e CPU_BIG_ENDIAN)
	;;
x86_64)
	KSRC=./linux-$VERSION-$VARIANT
	MAKE_ARGS=(ARCH=x86_64)
	NM=nm
	;;
x86_64-clang)
	KSRC=./linux-$VERSION-$VARIANT
	MAKE_ARGS=(ARCH=x86_64 CC=clang)
	NM=nm
	;;
*)
	echo "unknown variant: $VARIANT" >&2
	exit 2
	;;
esac
ARCH=${MAKE_ARGS[0]#ARCH=}
SRCARCH=${ARCH/x86_64/x86}

echo "Testing kernel $VERSION build ($VARIANT)"

prepare_kernel() {
	local tarball
	mkdir -p kernel-downloads
	tarball=$(ls kernel-downloads/linux-"$VERSION".*.tar.xz 2>/dev/null | sort -V | tail -n1 || true)
	if [ -z "$tarball" ]; then
		tarball=kernel-downloads/linux-$VERSION.tar.xz
		echo "Downloading Linux $VERSION..."
		wget -O "$tarball" \
			"https://cdn.kernel.org/pub/linux/kernel/v${VERSION%%.*}.x/linux-$VERSION.tar.xz"
	fi

	echo "Extracting $tarball..."
	mkdir "$KSRC"
	tar -xf "$tarball" -C "$KSRC" --strip-components=1

	echo "Preparing kernel $VERSION..."
	# -fcommon: older dtc sources fail to link with GCC >= 10
	make -C "$KSRC" "${MAKE_ARGS[@]}" HOSTCFLAGS="-fcommon" defconfig
	# Distribution kernels enable wireless extensions; defconfig does not.
	# USB_ZD1201 selects WIRELESS_EXT and WEXT_PRIV.
	"$KSRC"/scripts/config --file "$KSRC/.config" -e CFG80211_WEXT \
		-e WLAN_VENDOR_ZYDAS -m USB_ZD1201 "${KCONFIG_OPTS[@]}"
	make -C "$KSRC" "${MAKE_ARGS[@]}" HOSTCFLAGS="-fcommon" olddefconfig
	# extract-cert needs OpenSSL headers that may be missing; it is not
	# needed for building external modules.
	printf '#include <stdio.h>\nint main(void) { return 0; }\n' > "$KSRC/scripts/extract-cert.c"
	make -C "$KSRC" "${MAKE_ARGS[@]}" HOSTCFLAGS="-fcommon" -j"$JOBS" modules_prepare
}

[ -d "$KSRC" ] || prepare_kernel

make "${MAKE_ARGS[@]}" KSRC="$KSRC" clean >/dev/null
make "${MAKE_ARGS[@]}" KSRC="$KSRC" -j"$JOBS" "${DRIVER_ARGS[@]}" modules

# The test kernels are not fully built, so modpost cannot tell missing
# driver symbols from kernel symbols. Check undefined symbols against the
# symbols exported by the kernel source instead.
EXPORTS="$KSRC/.rtw-exports"
if [ ! -s "$EXPORTS" ]; then
	{
		grep -rhoE --include='*.[chS]' 'EXPORT_SYMBOL(_GPL|_NS|_NS_GPL)?\(\s*\w+' "$KSRC" |
			sed -E 's/.*\(\s*//'
		# exports generated by token pasting: accept identifiers declared
		# in the kernel's public headers
		grep -rhoE --include='*.h' '\b[A-Za-z_][A-Za-z0-9_]*\b' "$KSRC/include" \
			"$KSRC/arch/${SRCARCH}/include"
	} | LC_ALL=C sort -u > "$EXPORTS"
fi
missing=$("$NM" -u 8192eu.ko | awk '{print $2}' | LC_ALL=C sort -u | LC_ALL=C comm -23 - "$EXPORTS" |
	grep -vE '^(__[a-z0-9_]*|_mcount|memcpy|memset|memmove|memcmp|strlen)$' || true)
if [ -n "$missing" ]; then
	echo "✗ Unresolved symbols (not exported by Linux $VERSION):"
	echo "$missing"
	exit 1
fi

if [ -f 8192eu.ko ]; then
	echo "✓ Successfully built 8192eu.ko for $VERSION ($VARIANT)"
	ls -lh 8192eu.ko
else
	echo "✗ Build failed - module not found"
	exit 1
fi
